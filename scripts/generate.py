#!/usr/bin/env python3
"""Generate the SDK from the pinned public contract without network access."""

import argparse
import hashlib
import html
import json
import re
import sys
import unicodedata
from pathlib import Path
from urllib.parse import urljoin, urlsplit


ROOT = Path(__file__).resolve().parent.parent
MARKER = '// <auto-generated/>\n'
VERBS = {'get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'}
SCHEMA_KEYS = {
    '$ref', 'type', 'format', 'properties', 'required', 'items',
    'additionalProperties', 'minimum', 'maximum', 'minLength', 'maxLength',
    'minItems', 'maxItems', 'enum', 'const', 'anyOf', 'oneOf', 'allOf',
    'uniqueItems', 'minProperties', 'maxProperties', 'propertyNames', 'pattern',
    'nullable',
}
DOCS_ORIGIN = 'https://docs.raims.com'
DOCS_ROOT = DOCS_ORIGIN + '/br'
DOCS_API = DOCS_ROOT + '/api/'
INLINE_DOCUMENTATION = re.compile(
    r'(?P<code>(?P<ticks>`+)(?P<literal>.*?)(?P=ticks))'
    r'|\[(?P<label>[^\]]+)\]\((?P<href>[^)\s]+)\)', re.DOTALL)


def identifier(value):
    ascii_value = unicodedata.normalize('NFKD', value).encode('ascii', 'ignore').decode()
    result = ''.join(part[:1].upper() + part[1:] for part in re.findall(r'[A-Za-z0-9]+', ascii_value))
    if not result:
        raise ValueError('A public name could not be represented as a C# identifier.')
    return ('Value' + result) if result[0].isdigit() else result


def camel(value):
    value = identifier(value)
    result = value[:1].lower() + value[1:]
    return '@' + result if result in {'event', 'params', 'ref', 'out', 'in', 'class', 'namespace'} else result


def cs_string(value):
    return json.dumps(value, ensure_ascii=False)


def public_documentation_url(value):
    if urlsplit(value).scheme or value.startswith('//'):
        return value
    if value.startswith(('/br/', '/en/')):
        return DOCS_ORIGIN + value
    if value.startswith('/'):
        return DOCS_ROOT + value
    return urljoin(DOCS_API, value)


def inline_documentation(value):
    text = ' '.join(str(value).split())
    result = []
    position = 0
    for match in INLINE_DOCUMENTATION.finditer(text):
        result.append(html.escape(text[position:match.start()], quote=False))
        if match.group('code'):
            result.append('<c>' + html.escape(match.group('literal'), quote=False) + '</c>')
        else:
            url = html.escape(public_documentation_url(match.group('href')), quote=True)
            result.append('<see href="' + url + '">' + inline_documentation(match.group('label')) + '</see>')
        position = match.end()
    result.append(html.escape(text[position:], quote=False))
    return ''.join(result)


def documentation(value, indent='    ', tag='summary'):
    paragraphs = [part for part in re.split(r'\n\s*\n', str(value)) if part.strip()]
    if tag == 'remarks' or len(paragraphs) > 1:
        return (indent + '/// <' + tag + '>\n'
                + ''.join(indent + '/// <para>' + inline_documentation(part) + '</para>\n' for part in paragraphs)
                + indent + '/// </' + tag + '>\n')
    text = inline_documentation(value)
    return indent + '/// <' + tag + '>' + text + '</' + tag + '>\n'


def markdown(value):
    text = ' '.join(str(value).split())
    result = []
    position = 0
    for match in INLINE_DOCUMENTATION.finditer(text):
        result.append(html.escape(text[position:match.start()], quote=False))
        if match.group('code'):
            result.append(match.group('code'))
        else:
            result.append('[' + match.group('label') + '](' + public_documentation_url(match.group('href')) + ')')
        position = match.end()
    result.append(html.escape(text[position:], quote=False))
    return ''.join(result).replace('|', '\\|')


class Generator:
    def __init__(self):
        source = json.loads((ROOT / 'contracts/source.json').read_text(encoding='utf-8-sig'))
        raw = (ROOT / 'contracts/openapi.json').read_bytes()
        if hashlib.sha256(raw).hexdigest() != source['sha256']:
            raise ValueError('The pinned OpenAPI SHA-256 does not match contracts/source.json.')
        self.source = source
        self.spec = json.loads(raw)
        self.schemas = self.spec['components']['schemas']
        self.services = json.loads((ROOT / 'contracts/service-map.json').read_text(encoding='utf-8-sig'))
        reference = json.loads((ROOT / 'docs/reference.en.json').read_text(encoding='utf-8'))
        if not isinstance(reference, dict) or reference.get('locale') != 'en' or not isinstance(reference.get('translations'), dict):
            raise ValueError('The reference requires an English translation catalog.')
        self.reference_translations = reference['translations']
        if not all(isinstance(key, str) and key and isinstance(value, str) and value.strip()
                   for key, value in self.reference_translations.items()):
            raise ValueError('Reference translations must contain nonempty source and English text.')
        self.operations = {}
        self.outputs = {}
        self.input_nested = {}
        self.model_nested = {}
        self.enums = {}
        for path, item in self.spec['paths'].items():
            for method, operation in item.items():
                if method not in VERBS:
                    continue
                name = operation.get('operationId')
                if not name or name in self.operations:
                    raise ValueError('Every operation must have a unique operationId.')
                if operation.get('x-raims-availability', 'production') != 'production':
                    raise ValueError('The SDK may only consume published operations.')
                self.operations[name] = dict(operation, method=method.upper(), path=path,
                                             path_parameters=item.get('parameters', []))
        mapped = [op for methods in self.services.values() for op in methods.values()]
        names = list(self.operations) + list(self.services) + [name for methods in self.services.values() for name in methods]
        if any(not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name) for name in names):
            raise ValueError('Operation and service-map names must be valid C# identifiers.')
        if len(set(mapped)) != len(mapped) or set(mapped) != set(self.operations):
            raise ValueError('The service map must cover every operation exactly once.')
        if len(mapped) != source['operations']:
            raise ValueError('The operation count does not match contracts/source.json.')
        self.validate_schemas(self.schemas)
        for name, schema in self.schemas.items():
            if name.endswith('ListPage'):
                self.validate_pagination(name, schema)

    def resolve(self, schema):
        if '$ref' not in schema:
            return schema
        target = self.spec
        for part in schema['$ref'].split('/')[1:]:
            target = target[part.replace('~1', '/').replace('~0', '~')]
        return dict(target, **{k: v for k, v in schema.items() if k != '$ref'})

    def normalize(self, schema):
        if 'oneOf' in schema or 'allOf' in schema:
            raise ValueError('Unsupported composition: add explicit support before updating the contract.')
        if 'anyOf' not in schema:
            return schema
        branches = schema['anyOf']
        concrete = [item for item in branches if item.get('type') != 'null']
        if len(branches) != 2 or len(concrete) != 1:
            raise ValueError('Only a concrete schema combined with null can be represented.')
        result = dict(self.normalize(concrete[0]), **{k: v for k, v in schema.items() if k != 'anyOf'})
        result['nullable'] = True
        return result

    def validate_schemas(self, node):
        if isinstance(node, dict):
            self.normalize(node)
            if '$ref' in node:
                self.resolve(node)
            for value in node.values():
                self.validate_schemas(value)
        elif isinstance(node, list):
            for value in node:
                self.validate_schemas(value)

    def nullable(self, schema):
        schema = self.normalize(schema)
        return schema.get('nullable', False) or 'null' in self.types(schema)

    def validate_pagination(self, name, schema):
        expected = {
            'page_size': {'integer'}, 'has_next': {'boolean'},
            'has_previous': {'boolean'}, 'next_after': {'string', 'null'},
            'previous_before': {'string', 'null'},
        }
        properties = schema.get('properties', {})
        if set(properties) != set(expected) or set(schema.get('required', [])) != set(expected):
            raise ValueError('Pagination requires an explicit representation update: ' + name)
        for key, kinds in expected.items():
            if set(self.types(properties[key])) != kinds:
                raise ValueError('Pagination field type changed: ' + name + '.' + key)
        page_size = properties['page_size']
        if page_size.get('minimum', 0) < 0 or page_size.get('maximum', 2147483648) > 2147483647:
            raise ValueError('Pagination page_size exceeds the supported Int32 range: ' + name)

    @staticmethod
    def types(schema):
        value = schema.get('type', [])
        return value if isinstance(value, list) else [value]

    def type_name(self, schema, context, input_type=False, optional=False):
        schema = self.normalize(schema)
        nullable = self.nullable(schema) or optional
        if '$ref' in schema:
            name = schema['$ref'].split('/')[-1]
            if input_type:
                name = (name[:-7] if name.endswith('Request') else name) + 'DataOptions'
                self.input_nested.setdefault(name, self.resolve(schema))
            elif name.endswith('ListPage'):
                name = 'Pagination'
        else:
            types = [value for value in self.types(schema) if value != 'null']
            if len(types) > 1:
                raise ValueError('Unsupported schema type union: ' + context)
            kind = types[0] if types else None
            if kind == 'string':
                name = 'string'
            elif kind == 'boolean':
                name = 'bool'
            elif kind == 'integer':
                name = 'int' if schema.get('format') == 'int32' else 'long'
            elif kind == 'number':
                name = 'decimal'
            elif kind == 'array':
                name = 'List<' + self.type_name(schema['items'], context + 'Item', input_type) + '>'
            elif kind == 'object' and isinstance(schema.get('additionalProperties'), dict):
                name = 'Dictionary<string, ' + self.type_name(schema['additionalProperties'], context + 'Value', input_type) + '>'
            elif kind == 'object' and 'properties' in schema:
                name = context + ('DataOptions' if input_type else 'Data')
                (self.input_nested if input_type else self.model_nested).setdefault(name, schema)
            elif kind == 'object':
                name = 'Dictionary<string, JsonElement>'
            elif kind is None or kind == 'null':
                name = 'JsonElement'
            else:
                raise ValueError('Unsupported schema type: ' + str(kind))
        return name + ('?' if nullable else '')

    def add(self, relative, contents):
        if relative in self.outputs:
            raise ValueError('Duplicate generated output: ' + relative)
        self.outputs[relative] = contents.replace('\r\n', '\n')

    @staticmethod
    def source_file(contents):
        indented = '\n'.join('    ' + line if line else '' for line in contents.split('\n'))
        return MARKER + '#nullable enable\n\nusing System;\nusing System.Collections.Generic;\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\nusing System.Threading;\nusing System.Threading.Tasks;\n\nnamespace Raims\n{\n' + indented + '}\n'

    def input_class(self, name, schema, remarks=None):
        properties = self.resolve(schema).get('properties', {})
        text = documentation(schema.get('description', 'Parâmetros de ' + name + '.'), '')
        if remarks:
            text += documentation(remarks, '', 'remarks')
        text += 'public sealed class ' + name + ' : BaseOptions\n{\n'
        seen = set()
        for json_name, prop in properties.items():
            prop_name = identifier(json_name)
            if prop_name in seen:
                raise ValueError('Duplicate C# option property in ' + name)
            seen.add(prop_name)
            typename = self.type_name(prop, name + prop_name, True)
            text += documentation(prop.get('description', json_name))
            text += '    public Optional<' + typename + '> ' + prop_name + '\n    {\n'
            text += '        get => Get<' + typename + '>(' + cs_string(json_name) + ');\n'
            text += '        set => Set(' + cs_string(json_name) + ', value);\n    }\n\n'
            self.register_enum(name + prop_name, prop)
        text += '}\n'
        self.add('src/Raims/Options/' + name + '.cs', self.source_file(text))

    def collection_item(self, schema):
        properties = schema.get('properties', {})
        if set(properties) == {'list', 'page'} and properties['list'].get('type') == 'array':
            page_schema = self.resolve(properties['page'])
            expected = {'page_size', 'has_next', 'has_previous', 'next_after', 'previous_before'}
            if set(page_schema.get('properties', {})) == expected:
                return self.type_name(properties['list']['items'], 'CollectionItem')
        return None

    def model_class(self, name, schema):
        if name.endswith('ListPage'):
            return
        item = self.collection_item(schema)
        base = 'RaimsCollection<' + item + '>' if item else 'RaimsEntity'
        text = documentation(schema.get('description', 'Resposta da API: ' + name + '.'), '')
        text += 'public sealed class ' + name + ' : ' + base + '\n{\n'
        required = set(schema.get('required', []))
        seen = set()
        for json_name, prop in schema.get('properties', {}).items():
            if item and json_name in {'list', 'page'}:
                continue
            prop_name = identifier(json_name)
            if prop_name == name:
                prop_name += 'Value'
            if prop_name in seen:
                raise ValueError('Duplicate C# model property in ' + name)
            seen.add(prop_name)
            typename = self.type_name(prop, name + prop_name, optional=json_name not in required)
            initial = '' if typename.endswith('?') or typename in {'int', 'long', 'bool', 'decimal', 'JsonElement'} else ' = default!;'
            text += documentation(prop.get('description', json_name))
            text += '    [JsonInclude]\n    [JsonPropertyName(' + cs_string(json_name) + ')]\n'
            text += '    public ' + typename + ' ' + prop_name + ' { get; internal set; }' + initial + '\n\n'
            self.register_enum(name + prop_name, prop)
        text += '}\n'
        self.add('src/Raims/Models/' + name + '.cs', self.source_file(text))

    def register_enum(self, name, schema):
        schema = self.normalize(schema)
        if schema.get('type') == 'array':
            self.register_enum(name + 'Item', schema['items'])
            return
        raw_values = schema.get('enum', [])
        values = [value for value in raw_values if value is not None]
        if not values:
            return
        labels = schema.get('x-raims-enum-labels')
        if labels is not None and len(labels) == len(raw_values):
            labels = [label for label, value in zip(labels, raw_values) if value is not None]
        if labels is None:
            if not all(isinstance(value, str) for value in values):
                return
            labels = values
        if len(labels) != len(values):
            raise ValueError('Enum labels do not match values: ' + name)
        entries = []
        for label, value in zip(labels, values):
            if not isinstance(value, (str, int)) or isinstance(value, bool):
                raise ValueError('Unsupported enum constant type: ' + name)
            entries.append((identifier(label), value))
        if len({key for key, _ in entries}) != len(entries):
            raise ValueError('Enum labels produce duplicate C# identifiers: ' + name)
        self.enums[name] = entries

    def parameters(self, operation):
        result = {}
        for parameter in operation.get('path_parameters', []) + operation.get('parameters', []):
            parameter = self.resolve(parameter)
            if parameter['in'] not in {'path', 'query', 'header'}:
                raise ValueError('Unsupported parameter location: ' + parameter['in'])
            if parameter['in'] == 'header' and parameter['name'].lower() != 'idempotency-key':
                raise ValueError('A new request header requires explicit support: ' + parameter['name'])
            result[(parameter['in'], parameter['name'])] = parameter
        return list(result.values())

    def operation_metadata(self, operation):
        parameters = self.parameters(operation)
        body = operation.get('requestBody')
        if body:
            body = self.resolve(body)
            body_schema = body['content']['application/json']['schema']
            if '$ref' not in body_schema:
                raise ValueError('Request bodies must use a named schema.')
            body = body_schema['$ref'].split('/')[-1]
        responses = {}
        for status, response in operation['responses'].items():
            if not status.startswith('2'):
                continue
            schema = self.resolve(response).get('content', {}).get('application/json', {}).get('schema')
            if schema is not None and '$ref' not in schema:
                raise ValueError('Successful responses must use a named schema.')
            responses[status] = schema['$ref'].split('/')[-1] if schema else None
        if not responses:
            raise ValueError('Every operation must declare a successful response.')
        return {
            'method': operation['method'], 'path': operation['path'],
            'idempotency': any(p['in'] == 'header' and p['name'].lower() == 'idempotency-key' for p in parameters),
            'body': body,
            'bodyRequired': operation.get('requestBody', {}).get('required', False),
            'query': {p['name']: self.clean_schema(p['schema']) for p in parameters if p['in'] == 'query'},
            'responses': responses,
        }

    def query_documentation_schema(self, operation):
        parameters = [parameter for parameter in self.parameters(operation) if parameter['in'] == 'query']
        properties = {}
        for parameter in parameters:
            schema = dict(parameter['schema'])
            if parameter.get('description'):
                schema['description'] = parameter['description']
            properties[parameter['name']] = schema
        return {'type': 'object', 'properties': properties,
                'required': [parameter['name'] for parameter in parameters if parameter.get('required', False)]}

    def clean_schema(self, schema):
        if not isinstance(schema, dict):
            return schema
        result = {}
        for key, value in schema.items():
            if key not in SCHEMA_KEYS:
                continue
            if key == 'properties':
                result[key] = {name: self.clean_schema(prop) for name, prop in value.items()}
            elif isinstance(value, dict):
                result[key] = self.clean_schema(value)
            elif isinstance(value, list):
                result[key] = [self.clean_schema(item) if isinstance(item, dict) else item for item in value]
            else:
                result[key] = value
        return result

    def response_closure(self):
        names = set()
        def visit(node):
            if isinstance(node, dict):
                if '$ref' in node and node['$ref'].startswith('#/components/schemas/'):
                    name = node['$ref'].split('/')[-1]
                    if name not in names:
                        names.add(name)
                        visit(self.schemas[name])
                for item in node.values():
                    visit(item)
            elif isinstance(node, list):
                for item in node:
                    visit(item)
        for operation in self.operations.values():
            visit(operation['responses'])
        return names

    def reference_markdown(self, value):
        if not value:
            return ''
        if value not in self.reference_translations:
            raise ValueError('Missing English reference translation: ' + value)
        return markdown(self.reference_translations[value])

    def generate(self):
        metadata = {name: self.operation_metadata(operation) for name, operation in self.operations.items()}
        docs = ['# Endpoint reference', '', '<!-- Generated by scripts/generate.py. -->', '',
                'This reference covers the ' + str(len(metadata)) + ' endpoints in the pinned contract.',
                'Each method has a synchronous version and a version with the `Async` suffix.',
                'Asynchronous methods accept `CancellationToken`; both forms accept `RequestOptions`.',
                'Monetary values use integer cents; resource dates use Unix seconds UTC.',
                'A `202` response requires tracking the resource and does not confirm financial completion.', '']
        operation_symbols = {}
        for service, methods in self.services.items():
            first_operation = self.operations[next(iter(methods.values()))]
            resource_name = first_operation.get('tags', [service])[0]
            text = documentation('Operações de ' + resource_name.lower() + '.', '')
            text += 'public sealed class ' + service + 'Service : BaseService\n{\n'
            text += '    internal ' + service + 'Service(ApiRequestor requestor) : base(requestor) { }\n\n'
            docs += ['## ' + service, '']
            for method, op_id in methods.items():
                op = self.operations[op_id]
                meta = metadata[op_id]
                query = meta['query']
                body = meta['body']
                response_names = list(dict.fromkeys(meta['responses'].values()))
                response = next((r for r in response_names if r), 'EmptyResponse')
                if len(response_names) > 1:
                    signatures = [self.schemas[r].get('properties', {}) for r in response_names if r]
                    if len(signatures) != len(response_names) or len({json.dumps({k: self.clean_schema(v) for k, v in x.items()}, sort_keys=True) for x in signatures}) > 1:
                        if op_id != 'RevokeCharge':
                            raise ValueError('Successful response variants require explicit representation: ' + op_id)
                    if op_id == 'RevokeCharge':
                        shapes = [self.schemas[r]['properties'] for r in response_names]
                        if not all(set(shape) == set(shapes[0]) for shape in shapes):
                            raise ValueError('Revocation response properties changed.')
                        without_constants = [
                            {name: {k: v for k, v in self.clean_schema(prop).items() if k != 'const'}
                             for name, prop in shape.items()}
                            for shape in shapes
                        ]
                        if len({json.dumps(shape, sort_keys=True) for shape in without_constants}) != 1:
                            raise ValueError('Revocation response field types changed.')
                option_class = op_id + 'Options' if body or query else None
                option_schema = dict(self.schemas[body]) if body else self.query_documentation_schema(op)
                option_schema['description'] = op.get('summary', 'Parâmetros de ' + op_id).rstrip('.') + '.'
                if option_class:
                    self.input_class(option_class, option_schema, op.get('description'))
                paths = [p for p in self.parameters(op) if p['in'] == 'path']
                signature = ['string ' + camel(p['name']) for p in paths]
                if option_class:
                    signature += [option_class + (' options' if body and meta['bodyRequired'] else '? options = null')]
                signature += ['RequestOptions? requestOptions = null', 'CancellationToken cancellationToken = default']
                arguments = [camel(p['name']) for p in paths]
                if option_class:
                    arguments.append('options')
                arguments += ['requestOptions', 'cancellationToken']
                signature = ', '.join(signature)
                text += documentation(op.get('summary', op_id))
                if op.get('description'):
                    text += documentation(op['description'], tag='remarks')
                text += '    public ' + response + ' ' + method + '(' + signature + ')\n'
                text += '        => ' + method + 'Async(' + ', '.join(arguments) + ').ConfigureAwait(false).GetAwaiter().GetResult();\n\n'
                text += documentation(op.get('summary', op_id))
                if op.get('description'):
                    text += documentation(op['description'], tag='remarks')
                text += '    public Task<' + response + '> ' + method + 'Async(' + signature + ')\n'
                path_argument = 'null' if not paths else 'new Dictionary<string, string> { ' + ', '.join('{ ' + cs_string(p['name']) + ', ' + camel(p['name']) + ' }' for p in paths) + ' }'
                text += '        => RequestAsync<' + response + '>(' + cs_string(op_id) + ', ' + path_argument + ', ' + ('options' if option_class else 'null') + ', requestOptions, cancellationToken);\n\n'
                member = 'Simulations.' + service[len('Simulation'):] if service.startswith('Simulation') else service
                operation_symbols[op_id] = {'service': service + 'Service', 'member': member,
                                             'method': method, 'options': option_class, 'response': response}
                docs += ['### ' + member + '.' + method + 'Async', '', '`' + meta['method'] + ' ' + meta['path'] + '`', '',
                         self.reference_markdown(op.get('summary', op_id)).rstrip('.') + '.', '',
                         self.reference_markdown(op.get('description', '')), '',
                         '- Operation: `' + op_id + '`.',
                         '- Return type: `' + response + '`; HTTP ' + ', '.join('`' + k + '`' for k in meta['responses']) + '.',
                         '- Idempotency: ' + ('accepts `RequestOptions.IdempotencyKey`.' if meta['idempotency'] else 'does not accept `IdempotencyKey`.'), '']
                if paths:
                    docs += ['Path arguments: ' + ', '.join('`' + camel(p['name']) + '`' for p in paths) + '.', '']
                if option_class:
                    docs += ['Options: `' + option_class + '` (' + ('JSON' if body else 'query') + ').', '',
                             '| C# property | HTTP field | Type | Required | Description |', '| --- | --- | --- | --- | --- |']
                    required = set(option_schema.get('required', []))
                    for name, prop in option_schema.get('properties', {}).items():
                        typename = self.type_name(prop, option_class + identifier(name), True)
                        docs.append('| `' + identifier(name) + '` | `' + name + '` | `Optional<' + typename + '>` | ' + ('Yes' if name in required else 'No') + ' | ' + self.reference_markdown(prop.get('description', '')) + ' |')
                    docs.append('')
                docs += ['Omitting a property keeps it absent. To send JSON `null`,',
                         'assign `new Optional<T>(null)` to an option whose type `T` allows null.', ''] if body else []
            text += '}\n'
            self.add('src/Raims/Services/' + service + 'Service.cs', self.source_file(text))
        for name in sorted(self.response_closure()):
            self.model_class(name, self.schemas[name])
        while self.input_nested:
            name = sorted(self.input_nested)[0]
            schema = self.input_nested.pop(name)
            self.input_class(name, schema)
        while self.model_nested:
            name = sorted(self.model_nested)[0]
            schema = self.model_nested.pop(name)
            self.model_class(name, schema)
        constants = documentation('Valores nomeados do contrato público. Os campos de resposta também aceitam valores futuros.', '')
        constants += 'public static class EnumValues\n{\n'
        for name, entries in sorted(self.enums.items()):
            constants += documentation(name)
            constants += '    public static class ' + name + '\n    {\n'
            for key, value in entries:
                constants += documentation('Valor da API: ' + str(value) + '.', '        ')
                constants += '        public const ' + ('string' if isinstance(value, str) else 'int') + ' ' + key + ' = ' + cs_string(value) + ';\n'
            constants += '    }\n\n'
        constants += '}\n'
        self.add('src/Raims/Generated/EnumValues.cs', self.source_file(constants))
        self.add('src/Raims/Generated/contract.json', json.dumps({'operations': metadata, 'schemas': {k: self.clean_schema(v) for k, v in self.schemas.items()}}, ensure_ascii=False, sort_keys=True, indent=2) + '\n')
        self.add('src/Raims/Generated/symbols.json', json.dumps(operation_symbols, sort_keys=True, indent=2) + '\n')
        self.add('docs/reference.md', '\n'.join(docs))

    def write(self, check):
        expected = set(self.outputs)
        actual = set()
        for directory in ['Models', 'Options', 'Services', 'Generated']:
            folder = ROOT / 'src/Raims' / directory
            if folder.exists():
                for file in folder.rglob('*'):
                    if file.is_file():
                        relative = file.relative_to(ROOT).as_posix()
                        if relative != 'src/Raims/Services/SimulationsService.cs':
                            actual.add(relative)
        stale = sorted(actual - expected)
        drift = sorted(path for path, content in self.outputs.items()
                       if not (ROOT / path).exists() or (ROOT / path).read_bytes() != content.encode('utf-8'))
        if check and (drift or stale):
            print('Generated output differs:', file=sys.stderr)
            for path in drift + stale:
                print('  ' + path, file=sys.stderr)
            return 1
        if not check:
            for path in stale:
                file = ROOT / path
                if file.suffix != '.cs' or not file.read_text(encoding='utf-8-sig').startswith(MARKER):
                    raise ValueError('Refusing to remove a non-generated file: ' + path)
            for path in stale:
                file = ROOT / path
                file.unlink()
            for path, content in self.outputs.items():
                destination = ROOT / path
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(content.encode('utf-8'))
        print(('Verified' if check else 'Generated') + ' ' + str(len(self.operations)) + ' operations and ' + str(len(self.outputs)) + ' files.')
        return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated output without changing files.')
    args = parser.parse_args()
    try:
        generator = Generator()
        generator.generate()
        return generator.write(args.check)
    except (KeyError, ValueError, TypeError, OSError) as error:
        print('Generation failed: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
